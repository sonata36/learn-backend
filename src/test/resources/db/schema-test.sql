CREATE TABLE IF NOT EXISTS products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 price DECIMAL(12,2) NOT NULL CHECK (price >= 0),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ordered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 total_price DECIMAL(14,2) NOT NULL DEFAULT 0 CHECK (total_price >= 0),
 deleted_at TIMESTAMP NULL DEFAULT NULL
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL,
 product_id BIGINT NOT NULL,
 product_name_snapshot VARCHAR(120) NOT NULL,
 unit_price DECIMAL(12,2) NOT NULL CHECK (unit_price >= 0),
 quantity INT NOT NULL CHECK (quantity > 0),
 CONSTRAINT fk_test_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE,
 CONSTRAINT fk_test_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT
);
